-- =====================================================================
-- Contenido: el motor de rutinas vive en tablas, no en codigo.
-- Cambiar ejercicios, duraciones o progresiones = cambiar filas.
-- =====================================================================

create table body_zone (
    code        varchar(20)  primary key,
    name        varchar(60)  not null,
    tagline     varchar(200) not null,
    sort_order  int          not null
);

create table exercise (
    slug          varchar(80)  primary key,
    name          varchar(120) not null,
    zone_code     varchar(20)  references body_zone (code),
    instructions  varchar(600) not null,
    voice_cue     varchar(300) not null,
    equipment     varchar(120),
    switch_sides  boolean      not null default false,
    video_url     varchar(400)
);

create table routine (
    slug       varchar(80)  primary key,
    name       varchar(120) not null,
    kind       varchar(20)  not null,
    zone_code  varchar(20)  references body_zone (code),
    summary    varchar(300) not null
);

create table routine_step (
    id                bigint generated by default as identity primary key,
    routine_slug      varchar(80) not null references routine (slug),
    step_order        int         not null,
    exercise_slug     varchar(80) not null references exercise (slug),
    duration_seconds  int         not null,
    rest_seconds      int         not null default 0,
    dosage            varchar(160),
    constraint uq_routine_step unique (routine_slug, step_order)
);

create table program (
    slug               varchar(80)  primary key,
    name               varchar(120) not null,
    zone_code          varchar(20)  not null references body_zone (code),
    summary            varchar(400) not null,
    sessions_per_week  int          not null
);

create table program_week (
    id            bigint generated by default as identity primary key,
    program_slug  varchar(80)  not null references program (slug),
    week_number   int          not null,
    title         varchar(120) not null,
    focus         varchar(300) not null,
    routine_slug  varchar(80)  not null references routine (slug),
    constraint uq_program_week unique (program_slug, week_number)
);

-- Quien ha validado el contenido (una sola fila). Mientras status = 'DRAFT'
-- la app avisa de que el contenido esta pendiente de revision profesional.
create table content_review (
    id                    int primary key,
    status                varchar(20)  not null,
    reviewer_name         varchar(120),
    reviewer_credentials  varchar(160),
    reviewed_on           date
);

-- =====================================================================
-- Jugadores y sus datos. No se guarda nombre ni email: el jugador se
-- identifica con un token aleatorio del que solo se almacena el hash.
-- =====================================================================

create table player (
    id               uuid        primary key,
    token_hash       varchar(64) not null unique,
    age              int         not null,
    weekly_hours     int         not null,
    skill_level      varchar(20) not null,
    consent_version  varchar(20) not null,
    consent_at       timestamp with time zone not null,
    created_at       timestamp with time zone not null
);

-- Dato de salud (RGPD): se borra en cascada con el jugador.
create table pain_entry (
    id           uuid        primary key,
    player_id    uuid        not null references player (id) on delete cascade,
    zone_code    varchar(20) not null references body_zone (code),
    score        int         not null check (score between 0 and 10),
    context      varchar(20) not null,
    recorded_at  timestamp with time zone not null
);

create index idx_pain_entry_player on pain_entry (player_id, recorded_at);

create table program_enrollment (
    id            uuid        primary key,
    player_id     uuid        not null references player (id) on delete cascade,
    program_slug  varchar(80) not null references program (slug),
    started_at    timestamp with time zone not null,
    active        boolean     not null
);

create index idx_enrollment_player on program_enrollment (player_id);

create table routine_completion (
    id             uuid        primary key,
    player_id      uuid        not null references player (id) on delete cascade,
    routine_slug   varchar(80) not null references routine (slug),
    enrollment_id  uuid        references program_enrollment (id) on delete cascade,
    week_number    int,
    completed_at   timestamp with time zone not null
);

create index idx_completion_player on routine_completion (player_id, completed_at);
create index idx_completion_enrollment on routine_completion (enrollment_id);
